<?php

namespace Godrade\Trame\Console;

use Godrade\Trame\Support\Palette;
use Illuminate\Console\Command;
use Illuminate\Filesystem\Filesystem;
use Symfony\Component\Console\Attribute\AsCommand;

#[AsCommand(name: 'trame:sources')]
final class SourcesCommand extends Command
{
    protected $signature = 'trame:sources {--path= : Output file (default: resources/css/trame-palette.css)}';

    protected $description = 'Generate the Tailwind @source inline() declarations for the configured palette';

    public function handle(Filesystem $files): int
    {
        $colors = Palette::colors();
        $path = (string) ($this->option('path') ?: resource_path('css/trame-palette.css'));

        $list = count($colors) === 1 ? $colors[0] : '{'.implode(',', $colors).'}';

        $content = "/* Generated by `php artisan trame:sources`. Do not edit: change config/trame.php and re-run. */\n";

        if ($colors !== []) {
            $content .= "@source inline(\"{text,bg,border}-{$list}\");\n";
        }

        $files->ensureDirectoryExists(dirname($path));
        $files->put($path, $content);

        $this->components->info(count($colors)." palette colours written to [{$path}].");

        return self::SUCCESS;
    }
}
